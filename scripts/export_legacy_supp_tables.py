# -*- coding: utf-8 -*-
"""Regenerate the five appendix tables of the stationary-campaign sections from
their committed records, so that nothing the supplement inputs is hand-maintained:

  results/p1_gci_iso/p1_gci_summary.csv            -> p1_table_isoenergetic_supp.tex
                                                       p1_table_corner_supp.tex
  results/p1_gci_iso/p1_ratios.csv                 -> p1_table_ratio_gci_supp.tex
  results/02_lambda_var/modal_audit_lambda_var.csv -> p2_table_bfirst_ablation.tex
  results/01_ReE_star_map/branch_runs.csv          -> p3_table_threshold.tex

Run from the repository root:  py scripts/export_legacy_supp_tables.py
"""
import csv
import os

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, ".."))
OUTDIR = os.path.join(REPO, "supplementary", "data_appendix")

SUMMARY = os.path.join(REPO, "results", "p1_gci_iso", "p1_gci_summary.csv")
RATIOS = os.path.join(REPO, "results", "p1_gci_iso", "p1_ratios.csv")
MODAL = os.path.join(REPO, "results", "02_lambda_var",
                     "modal_audit_lambda_var.csv")
RUNS = os.path.join(REPO, "results", "01_ReE_star_map", "branch_runs.csv")


def read(path):
    with open(path, newline="", encoding="utf-8") as fh:
        return list(csv.DictReader(fh))


def put(name, text):
    path = os.path.join(OUTDIR, name)
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(text)
    print("wrote %s (%d lines)" % (name, text.count("\n")))


CONTROL = {"uniform": "Uniform lid",
           "k1": "$k=1$ ($\\sin\\pi x$)",
           "k2": "$k=2$ ($\\sin 2\\pi x$)",
           "b1mean": "$B_1$ PINN mean",
           "uniform_smooth": "Uniform lid, $\\delta=0.05$ taper"}

ORDER = ["uniform", "k1", "k2", "b1mean"]


def isoenergetic_table(rows):
    by = {r["case"]: r for r in rows}
    ref = float(by["uniform"]["eps512"])
    body = []
    for case in ORDER:
        r = by[case]
        body.append("%s & %.3f & %.5f & %.5f & %.5f & %.2f & %.3f\\\\" % (
            CONTROL[case], float(r["E_r"]), float(r["eps128"]),
            float(r["eps256"]), float(r["eps512"]),
            100.0 * float(r["gci_fine"]), float(r["eps512"]) / ref))
    return "\n".join([
        "% Table P1: iso-energetic comparison at Re=500 (auto-generated",
        "% by scripts/export_legacy_supp_tables.py from results/p1_gci_iso/",
        "% p1_gci_summary.csv -- do not edit)",
        "\\begin{table}[t]",
        "\\centering",
        "\\caption{Grid convergence and iso-energetic comparison at $Re=500$ with "
        "matched actuation energy $E^*=0.25$ ($E_r=\\int_0^1 U_{\\mathrm{lid}}^2\\,dx$). "
        "$\\varepsilon$ is the integrated viscous dissipation; $\\mathrm{GCI}$ is the "
        "fine-grid Grid Convergence Index with $F_s=1.25$. The $B_1$ PINN mean control "
        "is used as computed ($E_r=0.2503$), i.e.\\ without rescaling. A flagged GCI "
        "means that the triple does not satisfy the smooth-error assumption; this is "
        "the case for the uniform lid, discussed in the corner-singularity study.}",
        "\\label{tab:s5_isoenergetic}",
        "\\small",
        "\\begin{tabular}{lcccccc}",
        "\\toprule",
        "Control & $E_r$ & $\\varepsilon_{128}$ & $\\varepsilon_{256}$ & "
        "$\\varepsilon_{512}$ & GCI$_{512}$ (\\%) & "
        "$\\varepsilon_{512}/\\varepsilon^{\\mathrm{unif}}_{512}$\\\\",
        "\\midrule"] + body + [
        "\\bottomrule",
        "\\end{tabular}",
        "\\end{table}",
        ""])


def corner_table(rows):
    by = {r["case"]: r for r in rows}
    ref = float(by["uniform"]["eps512"])
    names = {"uniform": "Uniform lid (discontinuous)",
             "uniform_smooth": "Uniform lid, $\\delta=0.05$ taper"}
    body = []
    for case in ["uniform", "uniform_smooth"]:
        r = by[case]
        body.append("%s & %.5f & %.5f & %.5f & %.2f & %.2f & %.3f\\\\" % (
            names[case], float(r["eps128"]), float(r["eps256"]),
            float(r["eps512"]), float(r["p_obs"]),
            100.0 * float(r["gci_fine"]), float(r["eps512"]) / ref))
    return "\n".join([
        "% Table P1c: corner-singularity control (auto-generated by",
        "% scripts/export_legacy_supp_tables.py from results/p1_gci_iso/",
        "% p1_gci_summary.csv -- do not edit)",
        "\\begin{table}[t]",
        "\\centering",
        "\\caption{Effect of the upper-corner velocity discontinuity on the grid "
        "convergence of the uniform lid at $Re=500$, $E^*=0.25$ and "
        "$N\\in\\{128,256,512\\}$. The tapered lid has the same unit plateau but a "
        "raised-cosine taper $U=\\frac12[1-\\cos(\\pi x/\\delta)]$ of width "
        "$\\delta=0.05$ at each upper corner, so its tangential velocity is "
        "continuous and the amplitude is rescaled to the same $E_r=0.25$. It is a "
        "different lid profile and does not replace the discontinuous lid in the "
        "iso-energetic ranking; it isolates the cause of the non-convergence.}",
        "\\label{tab:s5_corner}",
        "\\small",
        "\\begin{tabular}{lcccccc}",
        "\\toprule",
        "Control & $\\varepsilon_{128}$ & $\\varepsilon_{256}$ & $\\varepsilon_{512}$ "
        "& $p_{\\mathrm{obs}}$ & GCI$_{512}$ (\\%) & "
        "$\\varepsilon_{512}/\\varepsilon^{\\mathrm{unif}}_{512}$\\\\",
        "\\midrule"] + body + [
        "\\bottomrule",
        "\\end{tabular}",
        "\\end{table}",
        ""])


def dash(v, fmt="%.2f", scale=1.0):
    v = (v or "").strip()
    return fmt % (scale * float(v)) if v else "--"


def ratio_gci_table(rows):
    labels = {"uniform": "sharp lid", "uniform_smooth": "regularized lid"}
    order = {"k1": 0, "k2": 1, "b1mean": 2}
    body = []
    for ref in ["uniform", "uniform_smooth"]:
        sub = sorted([r for r in rows if r["ref"] == ref],
                     key=lambda r: order[r["case"]])
        for i, r in enumerate(sub):
            first = labels[ref] if i == 0 else ""
            body.append("%s & %s & %.3f & %.3f & %.3f & %s & %s & %s\\\\" % (
                first, CONTROL[r["case"]], float(r["ratio128"]),
                float(r["ratio256"]), float(r["ratio512"]),
                dash(r["p_obs"]), dash(r["gci_ratio"], scale=100.0),
                dash(r["ratio_exact"], fmt="%.3f")))
        if ref == "uniform":
            body.append("\\midrule")
    return "\n".join([
        "% Table P1b: GCI of dissipation ratios (auto-generated by",
        "% scripts/export_legacy_supp_tables.py from results/p1_gci_iso/",
        "% p1_ratios.csv -- do not edit)",
        "\\begin{table}[t]",
        "\\centering",
        "\\caption{Grid convergence of the dissipation ratio $\\varepsilon/"
        "\\varepsilon_{\\mathrm{ref}}$ at $Re=500$, $E^*=0.25$, formed on each grid "
        "before the Richardson extrapolation, so the quoted GCI refers to the "
        "quantity used in the text. Two references are used: the sharp uniform lid "
        "specified in the problem, whose own dissipation grows by $16\\%$ between "
        "$N=256$ and $N=512$ and has no usable GCI, and a corner-regularized uniform "
        "lid (cosine taper $\\delta=0.05$, the corner table above) at the same "
        "energy. With the sharp reference all three ratios drift by $18$--$21\\%$ "
        "over the triple and two of them fall outside the admissible range of the "
        "estimator; with the regularized reference all three converge with "
        "$p_{\\mathrm{obs}}\\in[0.8,1.1]$ and GCIs of $1.4$--$3.1\\%$. A dash means "
        "the estimator is not applicable.}",
        "\\label{tab:s5_ratio_gci}",
        "\\small",
        "\\begin{tabular}{llcccccc}",
        "\\toprule",
        "Reference & Control & ratio$_{128}$ & ratio$_{256}$ & ratio$_{512}$ & "
        "$p_{\\mathrm{obs}}$ & GCI$_{\\mathrm{ratio}}$ (\\%) & "
        "ratio$_{\\mathrm{exact}}$\\\\",
        "\\midrule"] + body + [
        "\\bottomrule",
        "\\end{tabular}",
        "\\end{table}",
        ""])


POINTS = [("1000", "1.0", "$Re=1000$, $E^*=1$", "1"),
          ("500", "0.25", "$Re=500$, $E^*=0.25$", "0.25"),
          ("700", "2.0", "$Re=700$, $E^*=2$", "2")]


def ablation_table(rows):
    body = []
    for re_, es, label, e_target in POINTS:
        sel = [r for r in rows
               if float(r["lambda_var"]) == 0.0
               and r["Re"] == re_ and r["E_star"] == es]
        f1 = [100.0 * float(r["f0"]) for r in sel]
        f2 = [100.0 * float(r["f1"]) for r in sel]
        ft = [100.0 * float(r["ft"]) for r in sel]
        first = sum(1 for r in sel if r["dominant_i"] == "0")
        body.append("%s & %s & %.1f--%.1f & $\\le%.2f$ & $\\le%.1f$ & %d/%d\\\\" % (
            label, e_target, min(f1), max(f1), max(f2), max(ft),
            first, len(sel)))
    return "\n".join([
        "% auto-generated by scripts/export_legacy_supp_tables.py from",
        "% results/02_lambda_var/modal_audit_lambda_var.csv -- do not edit",
        "\\begin{table}[t]",
        "\\centering",
        "\\caption{First-harmonic content of the \\(\\lambda_{\\mathrm{var}}=0\\) "
        "controls (five seeds per operating point, archived in "
        "\\texttt{results/02\\_lambda\\_var}). Every realization is dominated by the "
        "first spatial harmonic and is reclassified as \\(B_{\\mathrm{first}}\\); the "
        "second-harmonic fraction never exceeds \\(2.5\\%\\).}",
        "\\label{tab:bfirst_ablation}",
        "\\small",
        "\\begin{tabular}{lccccc}",
        "\\toprule",
        "Operating point & \\(E_r\\) target & \\(f_1\\) (\\%) & \\(f_2\\) (\\%) & "
        "\\(f_t\\) (\\%) & \\(B_{\\mathrm{first}}\\) seeds\\\\",
        "\\midrule"] + body + [
        "\\bottomrule",
        "\\end{tabular}",
        "\\end{table}",
        ""])


def classify(f2, ft, k, phi):
    if f2 > k * ft and f2 > phi:
        return "B1"
    if ft > k * f2 and ft > phi:
        return "B2"
    return "B3"


def threshold_table(rows):
    ks = [1.50, 1.75, 2.00, 2.50, 3.00]
    phis = [0.40, 0.50, 0.60]
    ref = [classify(float(r["f_2"]), float(r["f_t"]), 2.0, 0.5) for r in rows]
    body = []
    for k in ks:
        lab = [classify(float(r["f_2"]), float(r["f_t"]), k, 0.5) for r in rows]
        f = [100.0 * sum(1 for g in lab if g == c) / len(lab)
             for c in ("B1", "B2", "B3")]
        recl = sum(1 for a, b in zip(lab, ref) if a != b)
        tag = " (reference)" if k == 2.0 else ""
        body.append("dominance factor $k$ & %.2f%s & %.1f & %.1f & %.1f & %d\\\\"
                    % (k, tag, f[0], f[1], f[2], recl))
    for phi in phis:
        lab = [classify(float(r["f_2"]), float(r["f_t"]), 2.0, phi)
               for r in rows]
        f = [100.0 * sum(1 for g in lab if g == c) / len(lab)
             for c in ("B1", "B2", "B3")]
        recl = sum(1 for a, b in zip(lab, ref) if a != b)
        tag = " (reference)" if phi == 0.50 else ""
        body.append("floor $\\phi$ & %.2f%s & %.1f & %.1f & %.1f & %d\\\\"
                    % (phi, tag, f[0], f[1], f[2], recl))
    n = len(rows)
    return "\n".join([
        "% Table P3.5: sensitivity of the branch classification rule",
        "% (auto-generated by scripts/export_legacy_supp_tables.py from",
        "% results/01_ReE_star_map/branch_runs.csv -- do not edit)",
        "\\begin{table}[h]",
        "\\centering",
        "\\caption{Sensitivity of the pooled branch frequencies to the parameters of "
        "the dominance rule ($B_1$: $f_2>k f_t$ and $f_2>\\phi$; $B_2$: $f_t>k f_2$ "
        "and $f_t>\\phi$; $B_3$: otherwise). The reference rule is $k=2$, $\\phi=0.5$; "
        "one parameter is varied at a time. The last column counts the realizations "
        "whose label changes with respect to the reference.}",
        "\\label{tab:s3_threshold}",
        "\\small",
        "\\begin{tabular}{lcccccc}",
        "\\toprule",
        "Parameter & Value & $B_1$ (\\%) & $B_2$ (\\%) & $B_3$ (\\%) & "
        "Reclassified (of " + str(n) + ")\\\\ ",
        "\\midrule"] + body + [
        "\\bottomrule",
        "\\end{tabular}",
        "\\end{table}",
        ""])


def main():
    put("p1_table_isoenergetic_supp.tex", isoenergetic_table(read(SUMMARY)))
    put("p1_table_corner_supp.tex", corner_table(read(SUMMARY)))
    put("p1_table_ratio_gci_supp.tex", ratio_gci_table(read(RATIOS)))
    put("p2_table_bfirst_ablation.tex", ablation_table(read(MODAL)))
    put("p3_table_threshold.tex", threshold_table(read(RUNS)))


if __name__ == "__main__":
    main()
